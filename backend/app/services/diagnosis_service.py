import json
import logging
import time
from typing import Any

from sqlalchemy.orm import Session

from ..integrations.agent_adapter import AgentAdapter
from ..models import DiagnosisCase
from ..schemas import AnalyzeRequest

logger = logging.getLogger(__name__)


class DiagnosisService:
    def __init__(self, adapter: AgentAdapter | None = None) -> None:
        self.adapter = adapter or AgentAdapter()

    async def analyze(self, request: AnalyzeRequest, db: Session, user_id: str | None = None) -> dict[str, Any]:
        started = time.perf_counter()
        case = DiagnosisCase(user_id=user_id, input_text=request.clinical_text(), status="processing")
        db.add(case)
        db.commit()
        try:
            raw = await self.adapter.analyze(case.input_text)
            logger.info(
                "Diagnosis pipeline completed: status=%s diagnoses=%d literature=%s case_studies=%s",
                raw.get("status"),
                len(raw.get("top_5_diagnoses", [])),
                bool(raw.get("literature_validation")),
                bool(raw.get("case_study_validation")),
            )
            logger.info("Diagnosis model output:\n%s", json.dumps(raw, indent=2, default=str))
            result = self.normalize(case.id, raw, time.perf_counter() - started)
            case.status = "completed"
            case.result_json = json.dumps(result)
            db.commit()
            return result
        except Exception:
            case.status = "failed"
            db.commit()
            raise

    @staticmethod
    def normalize(case_id: str, raw: dict[str, Any], elapsed: float) -> dict[str, Any]:
        diagnoses = raw.get("top_5_diagnoses", raw.get("top_5_diagnoses_with_confidence", []))
        normalized = []
        top = raw.get("top_diagnosis") or {}
        recommendations = {
            "medications": top.get("medications", []),
            "precautions": top.get("precautions", []),
            "exercises": top.get("exercises", []),
            "diet": top.get("diet", []),
        }
        evidence_text = raw.get("literature_validation", "")
        case_study_text = raw.get("case_study_validation", "")
        for rank, item in enumerate(diagnoses or [], 1):
            if not isinstance(item, dict):
                continue
            score = item.get("confidence", item.get("ranking_score", 0.0))
            try:
                score = float(score)
            except (TypeError, ValueError):
                score = 0.0
            normalized.append({
                "condition": item.get("condition", "Unknown"),
                "rank": rank,
                "ranking_score": score,
                "score_type": "ranking_score",
                "supporting_evidence": [evidence_text] if evidence_text else [],
                "contradictory_evidence": [],
                "sources": [{
                    "title": "Literature validation",
                    "summary": evidence_text,
                    "details": "Generated by the model literature agent.",
                    "relation": "supports",
                }] if evidence_text else [],
                "explanation": item.get("description", ""),
                "uncertainty": "This is decision support, not a confirmed diagnosis.",
                "recommendations": recommendations if rank == 1 else {},
            })
        symptoms = raw.get("symptom_extraction", {}).get("extracted_symptoms", [])
        warnings = raw.get("safety_warnings", [])
        return {
            "case_id": case_id,
            "status": "completed",
            "symptoms": symptoms,
            "differential_diagnoses": normalized,
            "agent_results": {
                "symptom_understanding": {"status": "completed"},
                "diagnosis": {"status": "completed"},
                "literature": {"status": "completed" if raw.get("literature_validation") else "unavailable"},
                "case_retrieval": {"status": "completed" if raw.get("case_study_validation") else "unavailable"},
                "explainability": {"status": "completed" if raw.get("report") else "unavailable"},
            },
            "safety_warnings": warnings,
            "missing_information": [],
            "limitations": ["Ranking scores are not disease probabilities.", "Consult a qualified healthcare professional."],
            "execution_time_ms": round(elapsed * 1000, 2),
            "raw_summary": {
                "report": raw.get("report", ""),
                "literature_validation": raw.get("literature_validation", ""),
                "case_study_validation": raw.get("case_study_validation", ""),
            },
            "literature_review": raw.get("literature_validation", ""),
            "case_study_review": raw.get("case_study_validation", ""),
            "recommendations": recommendations,
            "case_comparisons": [{"label": "Case-study validation", "note": case_study_text}] if case_study_text else [],
        }
